-- MuzBingo — миграция на свои MP3 (запусти в Supabase → SQL Editor)
-- ============================================================================
-- Добавляет к треку путь/ссылку на ПОЛНЫЙ MP3-файл.
--
-- Зачем отдельная колонка, а не is_custom:
--   у «своих» треков id совпадает с именем файла в Storage, а у треков из iTunes
--   id — это идентификатор Apple. Чтобы привязать MP3 к УЖЕ существующему треку
--   (и не ломать плейлисты, где трек лежит снапшотом по id), нужен отдельный путь.
--
-- Формат значения:
--   • имя файла в Supabase Storage  → 'custom_1712345678.mp3'
--   • или полная ссылка (Cloudflare R2 и т.п.) → 'https://cdn.../track.mp3'
-- Приложение различает по наличию 'http' в начале.
--
-- Приоритет источников при воспроизведении:
--   1) mp3_path   — полная версия, ОФЛАЙН, точная позиция для «Продолжить»
--   2) youtube_id — полная версия, нужен интернет
--   3) preview    — 30 сек из iTunes
-- ----------------------------------------------------------------------------

alter table public.tracks
  add column if not exists mp3_path text;

comment on column public.tracks.mp3_path is
  'Имя файла в bucket audio-tracks ИЛИ полный https-URL (R2/CDN) с полной версией песни.';

