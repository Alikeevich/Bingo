-- ============================================================================
-- MuzBingo — полные версии песен через YouTube (запусти в Supabase → SQL Editor)
-- ============================================================================
-- Добавляет к треку ссылку на YouTube-видео с ПОЛНОЙ версией песни.
-- Используется в игре кнопкой «Продолжить (полная)»: когда толпа подпевает,
-- ведущий переключается с 30-сек превью на полную версию с той же секунды.
--
-- Приоритет источников при воспроизведении:
--   1) свой MP3 (isCustom)      — полная версия, работает ОФЛАЙН
--   2) youtube_id               — полная версия, нужен интернет
--   3) preview (iTunes/Deezer)  — 30 сек, кэшируется офлайн
-- ----------------------------------------------------------------------------

alter table public.tracks
  add column if not exists youtube_id text;

comment on column public.tracks.youtube_id is
  'YouTube video ID (11 символов) с полной версией песни. NULL = полной версии нет.';

